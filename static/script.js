const moodSelect = document.getElementById('mood');
const generateBtn = document.getElementById('generate-btn');
const outputCard = document.getElementById('output-card');
const outputDiv = document.getElementById('output');
const sourceBadge = document.getElementById('source-badge');
const historyList = document.getElementById('history-list');
const clearHistoryBtn = document.getElementById('clear-history-btn');
const themeToggleBtn = document.getElementById('theme-toggle');
const feedbackForm = document.getElementById('feedback-el');
const feedbackResponse = document.getElementById('feedback-response');

const HISTORY_KEY = 'motivationHistory';
const THEME_KEY = 'motivationTheme';
const MAX_HISTORY_ITEMS = 15;

function loadHistory() {
  try {
    const items = JSON.parse(localStorage.getItem(HISTORY_KEY) || '[]');
    return Array.isArray(items) ? items : [];
  } catch {
    return [];
  }
}

function renderHistory() {
  const items = loadHistory();
  historyList.innerHTML = '';

  if (items.length === 0) {
    const empty = document.createElement('li');
    empty.textContent = 'No messages yet. Pick a mood and click Get Motivation!';
    empty.style.opacity = '0.7';
    historyList.appendChild(empty);
    return;
  }

  for (const item of items) {
    const li = document.createElement('li');
    li.textContent = `[${item.mood}] "${item.message}"`;
    historyList.appendChild(li);
  }
}

function addToHistory(mood, message) {
  const items = loadHistory();
  items.unshift({ mood, message });
  localStorage.setItem(HISTORY_KEY, JSON.stringify(items.slice(0, MAX_HISTORY_ITEMS)));
  renderHistory();
}

async function getMotivation() {
  const mood = moodSelect.value;
  generateBtn.disabled = true;
  generateBtn.textContent = '⏳ Generating...';

  try {
    const response = await fetch('/generate_motivation', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ mood }),
    });

    const data = await response.json();
    if (!response.ok) {
      throw new Error(data.error || 'Failed to generate motivation.');
    }

    outputCard.classList.remove('hidden');
    outputDiv.textContent = `"${data.motivation}"`;
    sourceBadge.textContent =
      data.source === 'openai' ? '✨ Generated by OpenAI' : '⚡ Offline Fallback Mode';

    addToHistory(data.mood || mood, data.motivation);
  } catch (err) {
    outputCard.classList.remove('hidden');
    outputDiv.textContent = err.message || 'Could not reach the server.';
    sourceBadge.textContent = '⚠️ Error';
  } finally {
    generateBtn.disabled = false;
    generateBtn.textContent = '✨ Get Motivation';
  }
}

function applyTheme(isDark) {
  document.body.classList.toggle('dark-mode', isDark);
  themeToggleBtn.textContent = isDark ? '☀️ Light Mode' : '🌙 Dark Mode';
}

function toggleTheme() {
  const isDark = !document.body.classList.contains('dark-mode');
  localStorage.setItem(THEME_KEY, isDark ? 'dark' : 'light');
  applyTheme(isDark);
}

async function submitFeedback(event) {
  event.preventDefault();
  const nameInput = document.getElementById('name');
  const feedbackInput = document.getElementById('feedback');

  try {
    const response = await fetch('/feedback', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        name: nameInput.value,
        feedback: feedbackInput.value,
      }),
    });
    const data = await response.json();
    if (!response.ok) {
      throw new Error(data.error || 'Could not submit feedback.');
    }
    feedbackResponse.textContent = data.message;
    nameInput.value = '';
    feedbackInput.value = '';
  } catch (err) {
    feedbackResponse.textContent = err.message || 'Feedback submission failed.';
  }
}

generateBtn.addEventListener('click', getMotivation);
themeToggleBtn.addEventListener('click', toggleTheme);
feedbackForm.addEventListener('submit', submitFeedback);
clearHistoryBtn.addEventListener('click', () => {
  localStorage.removeItem(HISTORY_KEY);
  renderHistory();
});

applyTheme(localStorage.getItem(THEME_KEY) === 'dark');
renderHistory();
